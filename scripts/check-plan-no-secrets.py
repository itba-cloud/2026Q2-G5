#!/usr/bin/env python3
"""Fail if a Terraform plan or state holds a password in clear text.

terraform show -json includes sensitive values unmasked, so this reads them
directly. An attribute counts as a secret when its name says so or when
Terraform marks it sensitive (a sensitive input taints whatever uses it, such
as an S3 object's content); a variable, when it is declared sensitive.
Passwords must reach AWS through write-only attributes (secret_string_wo,
password_wo) or be generated by the service itself
(manage_master_user_password); either way they never land in the state.

    terraform plan -out=tfplan && terraform show -json tfplan > plan.json
    python3 scripts/check-plan-no-secrets.py plan.json

    terraform show -json > state.json          # an existing deployment
    python3 scripts/check-plan-no-secrets.py state.json

Only attribute and variable names are printed, never their values.
"""
import json
import re
import sys

# Attributes that carry a secret value. Write-only attributes (*_wo) are never
# stored, and *_version or flag attributes hold no secret. Booleans never do
# either, whatever their name (force_overwrite_replica_secret).
SECRET_NAME = re.compile(r"(^|_)(password|passwd|pass|secret_string|secret|private_key)$")
NOT_SECRET = re.compile(r"(_wo|_version|_arn|_id|_length|_policy)$|^manage_|^master_user_secret$|^force_overwrite_replica_secret$")


def secret_paths(value, path):
    """Yield the paths of attributes with a secret-like name and a value."""
    if isinstance(value, dict):
        for key, item in value.items():
            here = f"{path}.{key}"
            if SECRET_NAME.search(key) and not NOT_SECRET.search(key) and item not in (None, "", [], {}):
                if isinstance(item, (str, int, float)) and not isinstance(item, bool):
                    yield here
                    continue
            yield from secret_paths(item, here)
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from secret_paths(item, f"{path}[{index}]")


def sensitive_paths(values, markers, path):
    """Yield the paths Terraform marks sensitive that hold a value."""
    if markers is True:
        if values not in (None, "", [], {}):
            yield path
    elif isinstance(markers, dict) and isinstance(values, dict):
        for key, marker in markers.items():
            yield from sensitive_paths(values.get(key), marker, f"{path}.{key}")
    elif isinstance(markers, list) and isinstance(values, list):
        for index, (value, marker) in enumerate(zip(values, markers)):
            yield from sensitive_paths(value, marker, f"{path}[{index}]")


def resources(module):
    for resource in module.get("resources", []):
        yield resource
    for child in module.get("child_modules", []):
        yield from resources(child)


def sensitive_markers(resource):
    markers = resource.get("sensitive_values", {})
    values = resource.get("values", {})
    # The AWS provider marks every SSM value sensitive, including AWS's public
    # Amazon Linux AMI catalogue. Exempt only that public, non-SecureString ID.
    if (resource.get("mode") == "data" and resource.get("type") == "aws_ssm_parameter"
            and values.get("type") == "String"
            and values.get("name", "").startswith("/aws/service/ami-amazon-linux-latest/")
            and isinstance(values.get("value"), str)
            and re.fullmatch(r"ami-(?:[0-9a-f]{8}|[0-9a-f]{17})", values["value"])
            and isinstance(markers, dict)):
        return {key: marker for key, marker in markers.items() if key != "value"}
    return markers


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: check-plan-no-secrets.py <plan.json|state.json>")
    with open(sys.argv[1]) as handle:
        document = json.load(handle)

    if "planned_values" in document:
        if document.get("errored") or document.get("complete") is False:
            sys.exit("The plan is incomplete (planning failed or used -target). Run a full plan.")
        modules = [document["planned_values"].get("root_module", {})]
        modules.append(document.get("prior_state", {}).get("values", {}).get("root_module", {}))
        variables = document.get("variables", {})
        declared = document.get("configuration", {}).get("root_module", {}).get("variables", {})
    elif "values" in document:
        modules = [document["values"].get("root_module", {})]
        variables, declared = {}, {}
    else:
        sys.exit("Not a plan or state: pass the output of `terraform show -json [planfile]`.")

    found = set()
    for module in modules:
        for resource in resources(module):
            values = resource.get("values", {})
            found.update(secret_paths(values, resource["address"]))
            found.update(sensitive_paths(values, sensitive_markers(resource), resource["address"]))
    for name, variable in variables.items():
        secret = declared.get(name, {}).get("sensitive") or (SECRET_NAME.search(name) and not NOT_SECRET.search(name))
        if secret and variable.get("value") not in (None, "") and not isinstance(variable.get("value"), bool):
            found.add(f"var.{name}")

    if found:
        print("Secrets would be stored in the Terraform state:")
        print("\n".join(f"  - {path}" for path in sorted(found)))
        sys.exit(1)
    checked = sum(1 for module in modules for _ in resources(module))
    print(f"OK: no password in clear text ({checked} resource entries checked).")


if __name__ == "__main__":
    main()

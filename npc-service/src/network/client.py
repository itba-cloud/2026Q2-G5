"""
NPC Network Client: Manages asynchronous WebSocket connection with World Service,
updates the local WorldView, and dispatches actions generated by the Brain.
"""

import asyncio
import logging
import time
from collections import deque
from typing import Optional
import websockets
from websockets.exceptions import ConnectionClosed, WebSocketException

from src.network.protocol import MessageTypes, parse_incoming_message, create_message
from src.model.world_view import WorldView
from src.model.actions import (
    Action,
    MoveAction,
    ShootAction,
    HarvestAction,
    BuildAction,
    UseItemAction,
    IdleAction
)
from src.brain.base import Brain
from src.brain.behavior_tree.npc_tree import BehaviorTreeBrain

logger = logging.getLogger("NPCClient")


class NPCNetworkClient:
    """
    Headless synthetic player client.
    Connects to World Service via WebSocket and runs the decision loop.
    """

    def __init__(
        self,
        server_url: str,
        bot_name: str = "[NPC] Guardian",
        world_id: str = "",
        brain: Optional[Brain] = None,
        tick_rate_hz: float = 10.0,
        reconnect_delay_sec: float = 3.0,
    ):
        self.server_url: str = server_url
        self.bot_name: str = bot_name
        self.world_id: str = world_id
        self.brain: Brain = brain or BehaviorTreeBrain()
        self.tick_interval: float = 1.0 / max(1.0, tick_rate_hz)
        self.reconnect_delay_sec: float = reconnect_delay_sec

        self.world_view: WorldView = WorldView(bot_name=bot_name)
        self.ws: Optional[websockets.WebSocketClientProtocol] = None
        self._is_running: bool = False
        self._is_joined: bool = False
        self._tasks: list[asyncio.Task] = []

        # Rolling window of Brain decision latencies, in milliseconds. Bounded so a
        # long-lived bot cannot grow this without limit.
        self._decision_latencies_ms: deque[float] = deque(maxlen=200)
        self._decision_count: int = 0
        self._max_decision_latency_ms: float = 0.0

    @property
    def is_joined(self) -> bool:
        return self._is_joined

    def get_ai_latency_stats(self) -> dict:
        """
        Returns the latency profile of this bot's Brain, in milliseconds.

        This is the 'AI call latency' surfaced by the monitoring dashboard: the time
        the behavior tree spends turning a WorldView into a list of actions.
        """
        samples = sorted(self._decision_latencies_ms)
        if not samples:
            return {
                "avgMs": None,
                "p95Ms": None,
                "maxMs": None,
                "peakMs": round(self._max_decision_latency_ms, 3),
                "decisions": self._decision_count,
                "samples": 0,
            }

        p95_index = min(len(samples) - 1, int(0.95 * len(samples)))
        return {
            "avgMs": round(sum(samples) / len(samples), 3),
            "p95Ms": round(samples[p95_index], 3),
            # Windowed, like avgMs and p95Ms: an operator comparing the three must be
            # comparing the same span. The all-time high is reported as peakMs.
            "maxMs": round(samples[-1], 3),
            "peakMs": round(self._max_decision_latency_ms, 3),
            "decisions": self._decision_count,
            "samples": len(samples),
        }

    @property
    def status(self) -> str:
        if not self._is_running:
            return "STOPPED"
        if self._is_joined:
            return "ACTIVE"
        return "CONNECTING"

    async def start(self) -> None:
        """
        Starts the client lifecycle loop with automatic reconnection.
        """
        self._is_running = True
        logger.info(f"[{self.bot_name}] Starting client, target server: {self.server_url} (World: {self.world_id or 'unknown'})")

        while self._is_running:
            try:
                logger.info(f"[{self.bot_name}] Connecting to {self.server_url}...")
                async with websockets.connect(self.server_url, ping_interval=20, ping_timeout=20) as ws:
                    self.ws = ws
                    self._is_joined = False
                    logger.info(f"[{self.bot_name}] WebSocket connection established. Sending JOIN (isBot=True)...")

                    # 1. Send JOIN packet with isBot = True for server distinction
                    await self._send(MessageTypes.JOIN, {
                        "playerName": self.bot_name,
                        "isBot": True
                    })

                    # 2. Run Listen & Decision Loops concurrently
                    listen_task = asyncio.create_task(self._listen_loop())
                    decision_task = asyncio.create_task(self._decision_loop())
                    self._tasks = [listen_task, decision_task]

                    done, pending = await asyncio.wait(
                        self._tasks,
                        return_when=asyncio.FIRST_EXCEPTION
                    )

                    for task in pending:
                        task.cancel()

            except ConnectionClosed as e:
                logger.warning(f"[{self.bot_name}] WebSocket closed ({e}). Reconnecting in {self.reconnect_delay_sec}s...")
            except (ConnectionRefusedError, OSError, EOFError, WebSocketException, asyncio.TimeoutError) as e:
                logger.info(f"[{self.bot_name}] Server at {self.server_url} not ready yet ({e}). Retrying in {self.reconnect_delay_sec}s...")
            except Exception as e:
                logger.error(f"[{self.bot_name}] Unexpected error in client loop: {e}", exc_info=True)

            if self._is_running:
                await asyncio.sleep(self.reconnect_delay_sec)

    async def stop(self) -> None:
        """Stops the client and cleans up open connections."""
        logger.info(f"[{self.bot_name}] Stopping client...")
        self._is_running = False
        for task in self._tasks:
            task.cancel()
        if self.ws:
            await self.ws.close()
            self.ws = None

    async def _send(self, msg_type: str, payload: dict) -> None:
        """Sends a JSON message over the WebSocket connection."""
        if self.ws:
            raw = create_message(msg_type, payload)
            await self.ws.send(raw)

    async def _listen_loop(self) -> None:
        """Receives and processes incoming server messages."""
        async for raw_message in self.ws:
            parsed = parse_incoming_message(raw_message)
            if not parsed:
                continue

            msg_type, payload = parsed
            self._handle_server_message(msg_type, payload)

    def _handle_server_message(self, msg_type: str, payload: dict) -> None:
        """Dispatches server messages to update local WorldView."""
        if msg_type == MessageTypes.INIT:
            self._is_joined = True
            self.world_view.update_from_init(payload)
            logger.info(f"[{self.bot_name}] Successfully initialized in world '{payload.get('worldId')}' with ID '{self.world_view.bot_id}'")

        elif msg_type == MessageTypes.STATE_SYNC:
            self.world_view.update_from_sync(payload)

        elif msg_type == MessageTypes.RESOURCE_HARVESTED:
            res_id = payload.get("resourceId")
            if res_id:
                inv = payload.get("playerInventory") if payload.get("harvestedBy") == self.world_view.bot_id else None
                self.world_view.handle_resource_harvested(res_id, inv)

        elif msg_type == MessageTypes.STRUCTURE_BUILT:
            struct = payload.get("structure")
            if struct:
                inv = payload.get("playerInventory")
                self.world_view.handle_structure_built(struct, inv)

        elif msg_type == MessageTypes.STRUCTURE_DESTROYED:
            struct_id = payload.get("structureId")
            if struct_id:
                self.world_view.handle_structure_destroyed(struct_id)

        elif msg_type == MessageTypes.PLAYER_HIT:
            if payload.get("victimId") == self.world_view.bot_id:
                logger.debug(f"[{self.bot_name}] Took damage! Remaining HP: {payload.get('victimHp')}")

        elif msg_type == MessageTypes.PLAYER_DIED:
            if payload.get("playerId") == self.world_view.bot_id:
                logger.info(f"[{self.bot_name}] Died! Killed by {payload.get('killerName')}. Awaiting respawn...")
                self.world_view.is_dead = True

        elif msg_type == MessageTypes.PLAYER_RESPAWNED:
            if payload.get("playerId") == self.world_view.bot_id:
                logger.info(f"[{self.bot_name}] Respawned at ({payload.get('x')}, {payload.get('y')})")
                self.world_view.is_dead = False
                self.world_view.hp = float(payload.get("hp", 100))
                self.world_view.x = float(payload.get("x", self.world_view.x))
                self.world_view.y = float(payload.get("y", self.world_view.y))

        elif msg_type == MessageTypes.ERROR:
            logger.warning(f"[{self.bot_name}] Server Error: {payload.get('message')}")

    async def _decision_loop(self) -> None:
        """Fixed-rate ticker that queries the Brain and sends actions to the server."""
        while self._is_running:
            if self._is_joined and not self.world_view.is_dead:
                try:
                    # Timed around the Brain only: dispatching the resulting actions is
                    # network I/O, not inference, and would distort the reading.
                    decision_started_at = time.perf_counter()
                    actions = self.brain.decide_actions(self.world_view)
                    self._record_decision_latency(
                        (time.perf_counter() - decision_started_at) * 1000.0
                    )

                    for action in actions:
                        await self._execute_action(action)
                except Exception as e:
                    logger.error(f"[{self.bot_name}] Error in decision tick: {e}", exc_info=True)

            await asyncio.sleep(self.tick_interval)

    def _record_decision_latency(self, latency_ms: float) -> None:
        """Stores one Brain decision latency in the rolling window."""
        self._decision_latencies_ms.append(latency_ms)
        self._decision_count += 1
        if latency_ms > self._max_decision_latency_ms:
            self._max_decision_latency_ms = latency_ms

    async def _execute_action(self, action: Action) -> None:
        """Translates an Action value object into a network message."""
        if isinstance(action, MoveAction):
            await self._send(MessageTypes.MOVE, {
                "direction": {"x": action.dx, "y": action.dy}
            })

        elif isinstance(action, ShootAction):
            await self._send(MessageTypes.SHOOT, {
                "angle": action.angle
            })

        elif isinstance(action, HarvestAction):
            await self._send(MessageTypes.HARVEST, {
                "targetId": action.target_id
            })

        elif isinstance(action, BuildAction):
            await self._send(MessageTypes.BUILD, {
                "type": action.structure_type,
                "x": action.x,
                "y": action.y
            })

        elif isinstance(action, UseItemAction):
            await self._send(MessageTypes.USE_ITEM, {
                "item": action.item
            })

        elif isinstance(action, IdleAction):
            await self._send(MessageTypes.MOVE, {
                "direction": {"x": 0, "y": 0}
            })
